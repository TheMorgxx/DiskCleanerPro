namespace DiskCleaner.Core.Models;

/// <summary>
/// Уровень риска найденного элемента очистки. Влияет только на то, отмечен ли
/// он галочкой по умолчанию в UI — реальное удаление в любом случае проходит
/// через PathSafetyService и требует подтверждения пользователя.
/// </summary>
public enum CleanupRiskLevel
{
    /// <summary>
    /// Хорошо известный, официально задокументированный кэш конкретного
    /// приложения/системы (например %TEMP%, pip cache, JetBrains caches).
    /// Отмечается галочкой по умолчанию.
    /// </summary>
    Safe,

    /// <summary>
    /// Найдено эвристически (по имени папки, а не по точному известному пути)
    /// либо есть небольшой шанс задеть что-то нетипичное. Не отмечается по
    /// умолчанию — пользователь должен сам просмотреть список путей.
    /// </summary>
    Review,

    /// <summary>
    /// Требует ручного решения: системные категории уровня ОС (кэш Windows
    /// Update, Delivery Optimization), для которых нужны права администратора
    /// и/или которые теоретически могут повлиять на работу системных служб.
    /// Никогда не отмечается по умолчанию.
    /// </summary>
    Manual,
}
